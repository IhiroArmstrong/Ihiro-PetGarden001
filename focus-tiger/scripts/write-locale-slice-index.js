/**
 * Write src/locales/localeSliceModules.js from slices/*.json.
 * The file is gitignored. Dev, test, and postinstall regenerate it
 * so feature PRs never edit a shared import list.
 */
import { randomBytes } from 'node:crypto';
import { readdirSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { JS_CSS_HEADER } from './copyright-header.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SLICES_DIR = join(root, 'src', 'locales', 'slices');
export const MODULE_PATH = join(root, 'src', 'locales', 'localeSliceModules.js');
/** Same directory as MODULE_PATH so `./slices/*.json` imports still resolve. */
export const REWRITE_PROBE_PATH = join(
  root,
  'src',
  'locales',
  'localeSliceModules.rewrite-probe.js'
);
export const LOCALE_SLICE_INDEX_LOCK_ENV = 'FT_LOCALE_SLICE_INDEX_LOCKED';

/**
 * @param {string[]} filenames
 * @returns {string}
 */
export function renderLocaleSliceModule(filenames) {
  const note =
    '// Generated by scripts/write-locale-slice-index.js. Do not edit or commit.\n';
  if (filenames.length === 0) {
    return `${JS_CSS_HEADER}${note}export const LOCALE_SLICES = [];\n`;
  }
  const imports = filenames.map(
    (name, index) =>
      `import s${index} from './slices/${name}' with { type: 'json' };`
  );
  const list = filenames
    .map((name, index) => `{ filename: '${name}', data: s${index} }`)
    .join(', ');
  return `${JS_CSS_HEADER}${note}${imports.join('\n')}\n\nexport const LOCALE_SLICES = [${list}];\n`;
}

/**
 * @returns {string[]}
 */
export function listSliceFilenames() {
  try {
    return readdirSync(SLICES_DIR)
      .filter((name) => /^[a-z0-9]+(?:-[a-z0-9]+)*\.json$/.test(name))
      .sort();
  } catch {
    return [];
  }
}

/**
 * @param {string} [targetPath]
 * @returns {string}
 */
export function writeLocaleSliceIndex(targetPath = MODULE_PATH) {
  if (
    process.env[LOCALE_SLICE_INDEX_LOCK_ENV] === '1' &&
    targetPath === MODULE_PATH
  ) {
    throw new Error(
      'localeSliceModules.js is frozen during parallel tests; write a probe path instead'
    );
  }
  const filenames = listSliceFilenames();
  const body = renderLocaleSliceModule(filenames);
  const tmpPath = `${targetPath}.${randomBytes(8).toString('hex')}.tmp`;
  writeFileSync(tmpPath, body);
  renameSync(tmpPath, targetPath);
  return body;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeLocaleSliceIndex();
  console.log(`[locale:slices] wrote ${listSliceFilenames().length} slice(s)`);
}
